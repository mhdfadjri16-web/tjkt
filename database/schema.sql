-- Schema Website Jurusan TJKT - SMKN 1 Simpang Kiri
-- Charset utf8mb4. Jalankan lewat install.php (Tahap B) atau manual.
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS admins (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(50) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  nama VARCHAR(100) NOT NULL DEFAULT '',
  role ENUM('superadmin','editor') NOT NULL DEFAULT 'editor',
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  last_login DATETIME NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS profil_jurusan (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  identitas TEXT,
  visi TEXT,
  misi TEXT,            -- satu poin per baris
  keunggulan TEXT,      -- JSON: [{judul, deskripsi}]
  logo VARCHAR(255) NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS pengajar (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  nama VARCHAR(120) NOT NULL,
  jabatan VARCHAR(120) NOT NULL DEFAULT '',
  foto VARCHAR(255) NULL,
  urutan INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS kegiatan (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  judul VARCHAR(200) NOT NULL,
  slug VARCHAR(220) NOT NULL UNIQUE,
  ringkasan VARCHAR(300) NOT NULL DEFAULT '',
  deskripsi TEXT,
  tanggal DATE NOT NULL,
  tanggal_selesai DATE NULL,
  gambar VARCHAR(255) NULL,
  is_agenda TINYINT(1) NOT NULL DEFAULT 0,
  created_by INT UNSIGNED NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_tanggal (tanggal)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS galeri (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  tipe ENUM('foto','video') NOT NULL DEFAULT 'foto',
  kategori ENUM('praktek','fasilitas') NOT NULL DEFAULT 'praktek',
  url VARCHAR(255) NOT NULL DEFAULT '',   -- path upload, atau URL YouTube untuk video
  caption VARCHAR(200) NOT NULL DEFAULT '',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS flyer_pkl (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  nama_tempat VARCHAR(160) NOT NULL,
  deskripsi TEXT,
  alamat VARCHAR(255) NOT NULL DEFAULT '',
  bidang VARCHAR(160) NOT NULL DEFAULT '',   -- tambahan: pisahkan dengan koma
  kuota INT NULL,                            -- tambahan: jumlah siswa diterima
  gambar_flyer VARCHAR(255) NULL,
  kontak_mitra VARCHAR(160) NOT NULL DEFAULT '',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS mitra_industri (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  nama VARCHAR(160) NOT NULL,
  logo VARCHAR(255) NULL,
  website VARCHAR(255) NULL,
  urutan INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS pengaturan_situs (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  `key` VARCHAR(80) NOT NULL UNIQUE,
  `value` TEXT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS plugins (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  nama_plugin VARCHAR(80) NOT NULL UNIQUE,
  status_aktif TINYINT(1) NOT NULL DEFAULT 0,
  pengaturan TEXT NULL   -- JSON
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS chat_faq (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  pertanyaan VARCHAR(255) NOT NULL,
  kata_kunci VARCHAR(255) NOT NULL DEFAULT '',
  jawaban TEXT NOT NULL,
  is_populer TINYINT(1) NOT NULL DEFAULT 0,
  urutan INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS visitor_log (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  tanggal DATE NOT NULL,
  path VARCHAR(255) NOT NULL,
  hash_ip CHAR(64) NOT NULL,
  KEY idx_tanggal (tanggal)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS login_attempts (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(50) NOT NULL,
  ip VARCHAR(45) NOT NULL,
  waktu TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_waktu (waktu)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
